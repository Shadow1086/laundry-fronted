Page({
    data: {
        title: '', sections: [], contacting: false,
        operator: '内蒙古奢皮仕技术服务有限责任公司',
        privacyPhone: '13948437986',
    },
    onLoad(options = {}) {
        const privacy = options.type !== 'service';
        const title = privacy ? '隐私政策' : '用户服务协议';
        this.setData({ title, sections: privacy ? PRIVACY : SERVICE });
        wx.setNavigationBarTitle({ title });
    },
    contact() {
        if (this.data.contacting) return;
        this.setData({ contacting: true });
        wx.makePhoneCall({
            phoneNumber: this.data.privacyPhone,
            fail: (error) => {
                if (!/cancel/i.test(String(error && error.errMsg || ''))) {
                    wx.showToast({ title: '拨号失败，请联系 13948437986', icon: 'none' });
                }
            },
            complete: () => this.setData({ contacting: false }),
        });
    },
});
